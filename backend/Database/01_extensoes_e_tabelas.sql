-- pg_trgm: índices por trigramas para buscas com ILIKE '%texto%'.
DO $$
BEGIN
    CREATE EXTENSION IF NOT EXISTS pg_trgm;
EXCEPTION WHEN insufficient_privilege THEN
    RAISE NOTICE 'Sem permissão para criar pg_trgm; buscas por texto usarão varredura comum.';
END $$;

-- Histórico de entradas e saídas de estoque, alimentado por trigger (05_triggers.sql).
CREATE TABLE IF NOT EXISTS "MovimentacoesEstoque" (
    "Id"              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "LojaId"          integer      NOT NULL,
    "ProdutoId"       integer      NOT NULL,
    "EstoqueAnterior" integer      NOT NULL,
    "EstoqueNovo"     integer      NOT NULL,
    "Diferenca"       integer      NOT NULL,
    "Origem"          varchar(120) NOT NULL,
    "Usuario"         varchar(150) NULL,
    "Data"            timestamp without time zone NOT NULL DEFAULT now()
);

-- Restrições de domínio: o banco recusa estoque negativo e desconto negativo,
-- mesmo que a regra falhe na aplicação (defesa em profundidade).
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_produtos_estoque_nao_negativo') THEN
        ALTER TABLE "Produtos" ADD CONSTRAINT ck_produtos_estoque_nao_negativo CHECK ("Estoque" >= 0);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_produtos_preco_nao_negativo') THEN
        ALTER TABLE "Produtos" ADD CONSTRAINT ck_produtos_preco_nao_negativo CHECK ("Preco" >= 0);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_os_desconto_nao_negativo') THEN
        ALTER TABLE "OrdensServico" ADD CONSTRAINT ck_os_desconto_nao_negativo CHECK ("Desconto" >= 0);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_lojas_status') THEN
        ALTER TABLE "Lojas" ADD CONSTRAINT ck_lojas_status CHECK ("Status" IN ('Ativa', 'Suspensa'));
    END IF;
END $$;
